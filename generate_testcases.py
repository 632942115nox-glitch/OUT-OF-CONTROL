# ==================== 生成 Excel ====================
HEADER_FILL = PatternFill("solid", fgColor="1F3864")
HEADER_FONT = Font(color="FFFFFF", bold=True, size=11)
THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def style_header(ws, ncol):
    for c in range(1, ncol + 1):
        cell = ws.cell(row=1, column=c)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = BORDER
    ws.freeze_panes = "A2"


def build_markdown():
    """导出 Markdown 版测试用例（与 Excel 同源，供 AI/纯文本场景阅读）"""
    order, stat = [], {}
    for tc in test_cases:
        mod = tc[1]
        if mod not in stat:
            stat[mod] = {"总": 0, "P0": 0, "P1": 0, "P2": 0}
            order.append(mod)
        stat[mod]["总"] += 1
        if tc[3] in ("P0", "P1", "P2"):
            stat[mod][tc[3]] += 1

    L = []
    L.append("# 《失控 OUT OF CONTROL》测试用例\n")
    L.append("> 数据来源：`dungeon-guardian/index.html` 当前版本（B 版本 + 最新调整）  ")
    L.append("> 自动生成：由 `generate_testcases.py` 与 `DungeonGuardian_测试用例.xlsx` **同源生成**，请勿手动编辑  ")
    L.append("> 最后同步：2026-08-29\n")

    # 汇总统计
    L.append("## 一、汇总统计\n")
    L.append("| 模块 | 总用例 | P0 | P1 | P2 |")
    L.append("|------|-------|----|----|----|")
    for mod in order:
        s = stat[mod]
        L.append(f"| {mod} | {s['总']} | {s['P0']} | {s['P1']} | {s['P2']} |")
    L.append(f"| **合计** | **{len(test_cases)}** | "
             f"**{sum(1 for t in test_cases if t[3]=='P0')}** | "
             f"**{sum(1 for t in test_cases if t[3]=='P1')}** | "
             f"**{sum(1 for t in test_cases if t[3]=='P2')}** |\n")

    # 测试用例（按模块分组）
    L.append("## 二、测试用例\n")
    for mod in order:
        L.append(f"### {mod}\n")
        L.append("| 编号 | 用例名称 | 优先级 | 前置条件 | 测试步骤 | 预期结果 |")
        L.append("|------|---------|-------|---------|---------|---------|")
        for tc in test_cases:
            if tc[1] != mod:
                continue
            def clean(v):
                return str(v).replace("\n", "<br>").replace("|", "／")
            L.append(f"| {tc[0]} | {clean(tc[2])} | {tc[3]} | {clean(tc[4])} | {clean(tc[5])} | {clean(tc[6])} |")
        L.append("")

    # 版本对照
    L.append("## 三、版本对照（数值演进）\n")
    L.append("| 项目 | 旧版本 | 当前版本(B) | 调整理由 |")
    L.append("|------|-------|------------|---------|")
    for row in version_rows:
        L.append(f"| {row[0]} | {row[1]} | {row[2]} | {row[3]} |")
    L.append("")

    # Bug 记录
    L.append("## 四、Bug 记录（真实修复记录）\n")
    L.append("| Bug ID | 标题 | 严重程度 | 模块 | 实际结果 | 预期结果 | 处理结果 |")
    L.append("|--------|------|---------|------|---------|---------|---------|")
    for b in bug_records:
        def cl(v):
            return str(v).replace("\n", "<br>").replace("|", "／")
        L.append(f"| {b[0]} | {cl(b[1])} | {b[2]} | {b[4]} | {cl(b[7])} | {cl(b[8])} | {cl(b[9])} |")
    L.append("")

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "TEST_CASES.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("已生成:", out)
    return out


